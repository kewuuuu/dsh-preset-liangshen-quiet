import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const PROFILE = process.env.DSH_PROFILE || "C:\\Users\\kewu0\\AppData\\Roaming\\dsh-launcher\\dsh-packs\\pack-test\\profiles\\pack-test"
const DESC = "梁神模式的静默变体——不弹选择题，每轮以结论、方案对比、编号选项和推荐收尾；未明确要求执行时只做设计阶段提议，不动文件、不跑变更命令、不派实现子 agent。"
const here = path.dirname(fileURLToPath(import.meta.url))
const SRC = path.resolve(here, '..', 'presets', 'liangshen-quiet')
const DEST = path.join(PROFILE, 'presets-local', 'liangshen-quiet')

fs.rmSync(DEST, { recursive: true, force: true })
fs.mkdirSync(path.dirname(DEST), { recursive: true })
fs.cpSync(SRC, DEST, { recursive: true })

const yml = fs.readFileSync(path.join(SRC, 'agent.cordis.yml'), 'utf8')
const rewrite = (l) => {
  const m = /^(\s*)name:\s*'?\.\/([^'\n]+?)'?\s*$/.exec(l)
  return m ? m[1] + "name: '" + pathToFileURL(path.join(DEST, m[2])).href + "'" : l
}
const body = yml.split('\n').map((l) => (l.trim() === '' ? '' : '          ' + rewrite(l))).join('\n').trimEnd()

const begin = '# region:begin liangshen-quiet'
const end = '# region:end liangshen-quiet'
const region = [
  begin + ' (generated by ' + path.join(here, 'install.mjs') + ' — do not edit by hand)',
  '- insert:',
  '    - id: preset-liangshen-quiet',
  '      name: "@deepseek-ai/dsh-agent-preset"',
  '      config:',
  '        id: liangshen-quiet',
  '        name: "静默提案"',
  '        description: "' + DESC + '"',
  '        order: 5',
  '        plugins:',
  body,
  end,
].join('\n')

const patchPath = path.join(PROFILE, 'cordis.patch.yml')
let text = fs.readFileSync(patchPath, 'utf8')
if (text.includes(begin)) {
  const i = text.indexOf(begin)
  const j = text.indexOf(end) + end.length
  text = text.slice(0, i) + region + text.slice(j)
} else {
  text = text.trimEnd() + '\n\n' + region + '\n'
}
fs.writeFileSync(patchPath, text)
console.log('copied preset ->', DEST)
console.log('patch bytes:', text.length)
